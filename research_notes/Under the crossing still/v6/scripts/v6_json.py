"""Gather the v6 shot's record into v6/v6.json (from the project root, the project's venv):

    python -I v6_json.py <render_dir> <out.json>

The render dir holds still_v6.py's logs; v6/render.log holds the frames' times; v6/drowning_sound.json and
v6/drowning_encode.json are read from beside the output.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import composite_v6 as CV  # noqa: E402


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def frame_times(log):
    if not os.path.exists(log):
        return None
    ts = [float(m.group(1)) for m in re.finditer(r"^frame \d+ level [\d.]+ s ([\d.]+)$", open(log).read(), re.M)]
    if not ts:
        return None
    return {"frames_logged": len(ts), "mean_s": round(sum(ts) / len(ts), 2), "max_s": max(ts),
            "workers": 3, "note": "each frame drawn in numpy from the passes (no Blender per frame)"}


