"""Gather the v11 shot's record into v11/v11.json, with the flicker scan (from the project root, the project's venv):

    python -I v11_json.py <out.json> <v10_render_dir> <v5_render_dir> <v8_render_dir> <anim_dir> <frames_dir>

Reads, beside the output: drowning_encode.json, drowning_sound.json (v9's, copied), render.log; writes flicker.json.
The crossings drawn are counted by building the scene (as the render does), not copied.
"""
