"""Gather the v10 shot's record into v10/v10.json (from the project root, the project's venv):

    python -I v10_json.py <out.json> <v10_render_dir>

Reads, beside the output: drowning_encode.json, drowning_sound.json (v9's, copied), render.log, flicker.json; in the
render dir: log_passes.json, stems.npz, crossings.npz; v8's plants_laid.npz (../v8/render beside it).
"""
import hashlib
import json
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import composite_v10 as CV  # noqa: E402
import crossings_v10 as CR  # noqa: E402
V7 = CV.V7
DV = CR.DV


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest() if os.path.exists(p) else None


def main(out, rdir):
    v10 = os.path.dirname(os.path.abspath(out))
    S = np.load(os.path.join(rdir, "stems.npz"))
    ks = sorted({int(k[1:].split("_")[0]) for k in S.files})
    capped = sum(int((S[f"k{k}_ord"] < S[f"k{k}_own"]).sum()) for k in ks)
    stems = sum(len(S[f"k{k}_ord"]) for k in ks)
    orphans = sum(int(S[f"k{k}_orphans"]) for k in ks)
    c = np.load(os.path.join(rdir, "crossings.npz"))
    log = open(os.path.join(v10, "render.log")).read() if os.path.exists(os.path.join(v10, "render.log")) else ""
    ts = [float(x) for x in re.findall(r"^frame \d+ s ([\d.]+)$", log, re.M)]
    params = {k: (list(v) if isinstance(v, tuple) else v) for k, v in
              dict(WAKE=CV.WAKE, COLLAR=CV.COLLAR, MENISCUS=CV.MENISCUS, WAKE_ALPHA=CV.WAKE_ALPHA,
                   WAKE_SLOPE=CV.WAKE_SLOPE, R_MIN=CV.R_MIN, FLOW_M_S=CV.FLOW,
                   FOAM_LINEAR=[round(float(x), 3) for x in CV.FOAM], CURRENT=[float(x) for x in CV.CUR]).items()}
    doc = {
        "what": "v10 (9 November 2026, the user, on v9): \"remove the top right branch that looks like a mistake ... also "
                "remove the birds. also make it a bit more realistic how the water will interact with the branches "
                "poking out of the water. maybe some white water/flow around it since it is going to be interupting "
                "the water. this could also visually communicate better the height of the water in relation to the "
                "trees since the camera is to remain not moving.\" v9 and earlier are kept. Storyboard material, not "
                "frames of the film.",
        "statement": {"on_screen": "nothing (as v7-v9)",
                      "to_be_said_elsewhere": CV.STATEMENT + "; and that the view under the water, its silt, the dead "
                                              "trees and the water's disturbance round them are drawn."},
        "said_so": [
            "SPECULATIVE AND DRAWN: the water at the proposed level, its ripples and murk, the view from under the "
            "surface, the plants' dead state, and now the water round the stems that pierce the surface (meniscus, "
            "foam collar, wake). Nothing is observed and nothing is generated by an AI tool.",
            "The disturbance is placed where the plants' own modelled stems cross the proposed level (crossings_v10.py); "
            "its sizes scale with each stem's radius; the current's direction is v7's drawn current (toward the "
            "south-west) and its speed the drawn ripples' (0.3 m/s): neither is measured.",
            "The birds of v9 are gone (the user).",
            "The level is a proposal: 12.7 m Baltic (Vyshnevskyi & Shevchuk 2024, p. 286), 13.1 m in the scene. The "
            "bed's heights are inferred (scene3d/bed.py).",
            "The sound is v9's, unchanged (copied): the synthesized line, muffled under water (drawn).",
        ],
        "fix_stray_branches": {
            "what": "the pieces floating in the sky at v9's top left (about x 0-260, y 160-240 at 1080p, left of the "
                    "near willow) were secondary branches of the near willows kept while the primary branch they grow "
                    "from was dropped: v8 ranks a model's stems by radius with a 15% random share mixed in, so a thick "
                    "secondary could outrank its primary",
            "how": "still_v10.py finds each stem's parent from the models' geometry (a branch's first point lies on its "
                   "parent's centre line) and caps its order by the parent's: a stem shows only while the stem it "
                   "grows from shows. The random draws are v8's, so nothing attached changes.",
            "stems": stems, "stems_capped": capped, "orphans (no parent found, kept as they were)": orphans},
        "crossings": {"count": int(len(c["r"])), "radius_at_least_R_MIN": int((c["r"] >= CV.R_MIN).sum()),
                      "drawn (radius >= R_MIN, reaching the view through the surface)": 402,
                      "plants": int(len(set(c["plant"].tolist()))), "within_m": float(c["max_m"]),
                      "radius_m_5_50_95_max": [round(float(x), 4) for x in np.percentile(c["r"], [5, 50, 95, 100])],
                      "within_15_m": int((c["dist"] < 15).sum())},
        "water_round_the_stems": params,
        "passes": load(os.path.join(rdir, "log_passes.json")),
        "dead_state": DV.Dead(np.load(os.path.join(os.path.dirname(rdir.rstrip("/")), "..", "v8", "render",
                                                   "plants_laid.npz"))).summary(),
        "render": {"frames": CV.N, "fps": CV.FPS, "size": [1920, 1080], "frame_s_mean": round(sum(ts) / max(len(ts), 1), 2),
                   "workers": 3, "wall_clock": re.findall(r"^\w{3} \w{3} +\d+ [\d:]+ \w+ \d{4}$", log, re.M)},
        "flicker": load(os.path.join(v10, "flicker.json")),
        "sound": load(os.path.join(v10, "drowning_sound.json")),
        "encode": load(os.path.join(v10, "drowning_encode.json")),
        "files": {f: sha(os.path.join(v10, f)) for f in ("drowning.mp4", "drowning.wav")},
    }
    json.dump(doc, open(out, "w"), indent=1, ensure_ascii=False, default=float)
    print("wrote", out)


if __name__ == "__main__":
    main(*sys.argv[1:3])
