"""The vegetation of the flight south's look pass 2 (`look.vegetation`; decided with the user, 7 November 2026): plants
placed by rule from the dated passes and OpenStreetMap, grown with the record's date, never generated by an AI tool.

The models are the `under-the-crossing` stills' (plants.py, a copy of research_notes/Under the crossing still/
scripts/plants.py: procedural stems, branches, twigs and leaves; species from the sources on the drained bed;
representative shapes, said so), with one more level of detail for far trees (`plants.crown`). The rules are those
stills' (place_plants.py: the habitat of each 10 m pixel from the pass's own bands), applied to every dated pass of
the bed, so each plant has the pass on which it first appears:

- The drained bed (inside the reservoir's footprint, bed.npz): candidates on jittered grids, denser near the flight's
  track (the camera's ground track, `track`) and thinner and coarser far off. At each, the habitat on the passes of 19
  August 2023, 23 August 2024 and 28 August 2025 (GNDVI, NDMI, the pass's own water mask: place_plants.py's classes;
  read at a spot jittered by about 4 m so the 10 m pixels blur). A plant appears on the first of those passes where
  its layer's chance for that habitat comes up, and only if every later pass shows its spot vegetated and dry (never
  the pass's water, nor the water the bed's model saw that day). Its family is drawn from the latest pass's habitat mix
  (place_plants.py's). It fades in over the 40 days before that pass (as the pass's imagery does) and then grows with
  the date shown: trees by GROWTH (the sources' heights: bare in June 2023, about 7 m in 2025, the largest about 9 m by
  spring and autumn 2026; the 2023-24 values interpolated between them, said so), a later cohort a year younger per pass;
  shrubs, saplings and reeds reach their typical heights over the season they appear in (typical, not measured).
- The banks (outside the footprint): trees inside OpenStreetMap's woods, scrub and tree rows (raw/osm_vegetation.json,
  saved verbatim, fetched once) where the pass of 28 August 2025 shows vegetation there (GNDVI 0.4 or more and not
  water; on the strip south of the land, where only its colour is at hand, green at least red and darker than 130);
  shown on every date (mature trees; their species aren't mapped: willow and poplar models, representative, their
  heights typical of shelterbelts and shore trees, not measured). Fields stay the imagery.
- Never within EXCLUDE_PLANT_M of the plant's units (its site), within POND_CLEAR_M of the cooling pond (its shores
  and dam: nothing is added there; the pond is the 2025 pass's own open water outside the
  reservoir near the plant), nor within TOWER_CLEAR_M of a tower or caisson.
- Herbs and grasses under 1.5 m are not modelled: the camera never comes within about 165 m of the ground in frame
  (at 70 m, pitched 7° down), where they would be a few pixels; the passes' own pixels carry them.

Positions are a pattern drawn from 10 m pixels, not individual plants. vegetation.npz: the points (place, turn,
growth, level of detail) and the prototypes' meshes; build.py instances them with geometry nodes (the level of detail
and culling by the distance from the camera each frame).
"""

