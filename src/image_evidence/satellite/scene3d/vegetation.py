GROWTH = [(11, 0.0), (74, 0.08), (444, 0.45), (814, 1.0), (1097, 1.3), (1224, 1.35)]
GROWTH_SPAN = 1300.0
SEASON_D = 120.0     # shrubs, saplings and reeds: their height reached over this many days from 60 days before the pass
