HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import composite_v7 as CV  # noqa: E402


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def frame_times(log):
    if not os.path.exists(log):
        return None
    ts = [float(m.group(1)) for m in re.finditer(r"^frame \d+ level [\d.]+ s ([\d.]+)$", open(log).read(), re.M)]
    dates = re.findall(r"^\w{3} \w{3} +\d+ [\d:]+ \w+ \d{4}$", open(log).read(), re.M)
    return {"frames_logged": len(ts), "mean_s": round(sum(ts) / max(len(ts), 1), 2), "max_s": max(ts or [0]),
            "workers": 3, "wall_clock": dates}


