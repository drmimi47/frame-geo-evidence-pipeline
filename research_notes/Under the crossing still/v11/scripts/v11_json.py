def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest() if os.path.exists(p) else None


def flicker(fdir):
    prev, steps = None, []
    for k in range(CV.N):
        a = np.asarray(Image.open(f"{fdir}/f_{k:04d}.png").convert("L").resize((480, 270)), np.float32)
        if prev is not None:
            steps.append((round(float(np.abs(a - prev).mean()), 3), k))
        prev = a
    v = [s for s, _ in steps]
    return {"method": "mean absolute luminance step between consecutive frames at 480x270",
            "largest": sorted(steps, reverse=True)[:5], "median": round(float(np.median(v)), 3)}


