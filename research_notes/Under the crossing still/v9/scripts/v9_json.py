"""Gather the v9 shot's record into v9/v9.json (from the project root, the project's venv):

    python -I v9_json.py <out.json> <v9_render_dir>

Reads, beside the output: drowning_encode.json, drowning_sound.json, render.log; in the render dir: log_passes.json,
perch.json, and v8's plants_laid.npz (../v8/render beside it).
"""
import hashlib
import json
import math
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import composite_v9 as CV  # noqa: E402
import dead_v9 as DV  # noqa: E402
import birds_v9 as BD  # noqa: E402
V7 = CV.V7


def load(p):
    return json.load(open(p)) if os.path.exists(p) else None


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest() if os.path.exists(p) else None


def tolist(v):
    return [round(float(x), 4) for x in np.ravel(v)] if isinstance(v, np.ndarray) else v


def main(out, rdir):
    v9 = os.path.dirname(os.path.abspath(out))
    laid = os.path.join(os.path.dirname(rdir.rstrip("/")), "..", "v8", "render", "plants_laid.npz")
    D = DV.Dead(np.load(laid, allow_pickle=True))
    perch = load(os.path.join(rdir, "perch.json"))
    birds = []
    for b in BD.BIRDS:
        tip = perch["plants"][b["plant"]]
        foot = np.array(tip["top"][0][:3]) - np.array([0, 0, b["below"]])
        d = float(np.linalg.norm(foot - BD.EYE))
        i, j, _ = V7.project(foot[None], 1920, 1080)
        birds.append({"id": b["id"], "tree": {"plant": int(b["plant"]), "model": tip["proto"],
                                              "family": tip["fam"], "height_m": round(tip["h"], 2),
                                              "top_m": round(tip["top"][0][2], 2)},
                      "feet_m": [round(float(x), 3) for x in foot], "above_the_surface_m": round(float(foot[2]) - V7.LEVEL, 2),
                      "distance_m": round(d, 1), "feet_px_1080p": [round(float(i[0]), 1), round(float(j[0]), 1)],
                      "height_px_about": round(0.62 * b["scale"] * 960 / d, 1),
                      "facing_deg_from_camera_right": b["facing"], "head_keys_t_yaw_pitch": b["head"],
                      "wings_open_held_close_s": b["wings"]})
    passes = load(os.path.join(rdir, "log_passes.json"))
    log = open(os.path.join(v9, "render.log")).read() if os.path.exists(os.path.join(v9, "render.log")) else ""
    ts = [float(x) for x in re.findall(r"^frame \d+ s ([\d.]+)$", log, re.M)]
    murk = {k: tolist(v) for k, v in CV.MURK.items()}
    v7_murk = {k: tolist(getattr(V7, k)) for k in CV.MURK}
    doc = {
        "what": "v9 (8 November 2026, the user): \"instead of the water rising from the bottom up i want the start of v9 "
                "to already have the water at the full height of the river ... right after under-the-crossing this v9 "
                "will play and it will be a dramatic cut to the water already fully back\"; less murk so the two lines "
                "and their towers are a bit more visible; the camera where it is; the very little plants gone, a few "
                "bigger ones bare stems, the trees standing bare with only the strongest branches; a bird or two "
                "perched near the top of the tallest dead tree. v8, v7 (and v6, v5) are kept as they were. "
                "Storyboard material, not frames of the film.",
        "statement": {"on_screen": "nothing: no caption or key on the picture (as v7, v8)",
                      "to_be_said_elsewhere": CV.STATEMENT + "; and that the view under the water, its silt, the dead "
                                              "trees and the birds are drawn."},
        "said_so": [
            "SPECULATIVE AND DRAWN: the water at the proposed level, its ripples and murk, the view from under the "
            "surface, the plants' dead state and the two birds. Nothing is observed and nothing is generated by an AI "
            "tool: the plants are v3's procedural models with leaves and finer stems hidden, the scene the flight "
            "south's, the birds a few ellipsoids drawn in numpy.",
            "THE DEAD STATE IS A DRAWING, NOT A FORECAST: the herbs and grasses gone, a few of the taller shrubs and "
            "reeds as bare stems, every tree standing bare with only its thickest branches (which plants stand is a "
            "random pick among the taller ones). As general knowledge, to be checked against a source before the film "
            "says it (no source was read for this shot): drowned trunks often stand for years or decades in "
            "reservoirs, and their bare tops are used as perches by cormorants.",
            "THE BIRDS: great cormorants (birds_v4's species: 1,240 nests on six towers of these crossings in 2012, "
            "Sidorenko & Siokhin 2016), drawn perched on the two tallest dead tree tops in view, one turning its head, "
            "the other turning its head and holding its wings out to dry for about 6 s. Typical behaviour drawn, not a "
            "record; sizes typical (about 0.85 m long, 1.35 m across the wings). No colony is shown or implied at a tower.",
            "The level is a proposal: 12.7 m Baltic (Vyshnevskyi & Shevchuk 2024, p. 286), 13.1 m in the scene "
            "(EGM2008, Baltic +0.4 m), held from the first frame. The bed's heights are inferred (scene3d/bed.py).",
            "Less murk than v7/v8 and a calmer surface (values below): a drawing choice, so the towers and the lit "
            "wires read through the surface. The view through the surface is a drawn convention (Snell's window not "
            "drawn). The flow dashes are the film's drawing convention.",
            "The sound: v7's continued soundscape (only the synthesized line in these 15 s), muffled from the first "
            "sample (drawn).",
        ],
        "approach": {
            "passes": "still_v9.py, once (the plants stand still): v8's still_v8.py exec'd without its main (v3's models "
                      "and placement, v5's camera f, the losses as instancer attributes), every loss binary (nothing "
                      "moves), the plants in dead_v9's state: static2x.exr, pos2x.exr, matte.exr",
            "render_log": passes,
            "dead_state": {"by_kind": D.summary(), "tree_twig_share_dropped": DV.TWIG_TREE,
                           "tree_twig_share_dropped_within_m": list(DV.TWIG_NEAR),
                           "shrub_twig_share_dropped": DV.TWIG_SHRUB,
                           "shrubs_kept (height quantile, share)": list(DV.KEEP_SHRUB),
                           "reeds_kept (height quantile, share)": list(DV.KEEP_REED)},
            "composite": "composite_v9.py: v7's composite_v7.py imported unchanged; the level 13.1 m from frame 0, the "
                         "eye under it every frame (v7's below); the picture through the surface the dead plate at half "
                         "size with v7's moving pass (frames 900-1349, run on from under-the-crossing) and the birds, "
                         "what lies under the surface filled from round it there (v7 showed the stems near the eye "
                         "twice); under the surface greyed toward silt at once (under for years)",
            "murk_v9": murk, "murk_v7": v7_murk,
            "picture_through_the_surface_blur_px": {"v9": CV.SRC_BLUR, "v7": 1.2},
            "short_ripples_slope": {"v9": CV.FINE_RIPPLE_A, "v7": 0.03},
        },
        "birds": birds,
        "sound": load(os.path.join(v9, "drowning_sound.json")),
        "render": {"frames": CV.N, "fps": CV.FPS, "size": [1920, 1080], "frame_s_mean": round(sum(ts) / max(len(ts), 1), 2),
                   "frames_logged": len(ts), "workers": 3,
                   "wall_clock": re.findall(r"^\w{3} \w{3} +\d+ [\d:]+ \w+ \d{4}$", log, re.M)},
        "encode": load(os.path.join(v9, "drowning_encode.json")),
        "files": {f: sha(os.path.join(v9, f)) for f in ("drowning.mp4", "drowning.wav")},
    }
    json.dump(doc, open(out, "w"), indent=1, ensure_ascii=False, default=float)
    print("wrote", out)


if __name__ == "__main__":
    main(*sys.argv[1:3])
